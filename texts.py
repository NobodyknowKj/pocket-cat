def shop_text(cat: dict) -> str:
    lines = [f"🛒 فروشگاه\n\n🪙 سکه‌ی تو: {int(cat['coins'])}\n\n"]
    for item_id, item in SHOP_ITEMS.items():
        lines.append(f"{item['name']} — {item['price']} سکه\n{item['description']}\nاثر: {item['effect']}\n")
    lines.append("غذاها رو از منوی 🍗 غذا دادن بخر!")
    return "\n".join(lines)


def food_shop_text(cat: dict, inventory: dict) -> str:
    lines = [f"🍗 غذاها\n\n🪙 سکه‌ی تو: {int(cat['coins'])}\n\n"]
    for fid, f in FOODS.items():
        qty = inventory.get(fid, 0)
        lines.append(f"{f['name']} — {f['price']} سکه — کاهش گرسنگی: {f['hunger_reduction']}\nموجودی تو: {qty}\n")
    return "\n".join(lines)


